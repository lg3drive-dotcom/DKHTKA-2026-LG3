export function getStats(): ClassStats {
  const count = STUDENT_RECORDS.length;
  let matSum = 0;
  let matMax = -Infinity;
  let matMin = Infinity;
  let indoSum = 0;
  let indoMax = -Infinity;
  let indoMin = Infinity;

  STUDENT_RECORDS.forEach((student) => {
    matSum += student.matematika;
    if (student.matematika > matMax) matMax = student.matematika;
    if (student.matematika < matMin) matMin = student.matematika;

    indoSum += student.bahasaIndonesia;
    if (student.bahasaIndonesia > indoMax) indoMax = student.bahasaIndonesia;
    if (student.bahasaIndonesia < indoMin) indoMin = student.bahasaIndonesia;
  });

  return {
    totalStudents: count,
    matAverage: Math.round((matSum / count) * 100) / 100,
    matMax,
    matMin,
    indoAverage: Math.round((indoSum / count) * 100) / 100,
    indoMax,
    indoMin,
    overallAverage: Math.round(((matSum + indoSum) / (count * 2)) * 100) / 100,
  };
}
